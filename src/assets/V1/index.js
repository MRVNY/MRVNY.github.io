function onLoadDev() {

    var sidebar = document.getElementById("sidebar");
    var headertext = document.getElementById("header-text");

    if (window.innerWidth < window.innerHeight || window.innerWidth / window.innerHeight > 7 / 16) {
        headertext.parentNode.insertBefore(headertext, sidebar);
    }

    var ul = sidebar.getElementsByTagName("ul")[0];
    var body = document.getElementsByTagName("body");
    for (i = 0; i < devs.length; i++) {
        var entry = devs[i];

        //TABLE OF CONTENT
        var li = document.createElement("li");

        //a click
        var a = document.createElement("a");
        a.className = "click";
        a.href = "#" + entry.id;
        // a.onclick = function () { document.getElementById(arg).scrollIntoView({ behavior: 'smooth' });};
        a.innerHTML = entry.title;
        li.appendChild(a);
        li.appendChild(document.createElement("br"));

        //tags
        var tags = document.createElement("tag");
        tags.className = "tag";
        tags.innerHTML = entry.tags;
        li.appendChild(tags);

        ul.appendChild(li);

        //BLOCK
        var block = document.createElement("div");
        block.id = entry.id;
        block.className = "block";

        //h1 
        block.appendChild(document.createElement("h1")).innerHTML = entry.title;

        //div.text
        var text = document.createElement("div");
        text.className = "text";
        text.innerHTML = entry.text1 + "<br>";
        if (entry.text2 != undefined) text.innerHTML += "<h6>" + entry.text2 + "</h6>";
        else text.innerHTML += "<br>";

        block.appendChild(text);

        //p
        var p = document.createElement("p");
        if (entry.image != undefined) {
            var img = document.createElement("img");
            img.className = "img";
            img.src = "../portfolio/" + entry.image;
            p.appendChild(img);
        }
        else if (entry.youtube != undefined) {
            var iframe = document.createElement("iframe");
            iframe.src = entry.youtube;
            iframe.title = "YouTube video player";
            iframe.frameborder = "0";
            iframe.allow = "accelerometer; autoplay; clipboard-write; encrypted-media; gyroscope; picture-in-picture; web-share";
            iframe.allowFullscreen = true;
            p.appendChild(iframe);
        }

        block.appendChild(p);

        //button_row
        var button_row = document.createElement("button_row");
        if (entry.play != undefined) {
            var a = document.createElement("a");
            a.href = entry.play;
            a.className = "click";
            a.innerHTML = "Play Game";
            button_row.appendChild(a);
        }
        if (entry.code != undefined) {
            var a = document.createElement("a");
            a.href = entry.code;
            a.className = "click";
            a.innerHTML = "See Code";
            button_row.appendChild(a);
        }
        if (entry.report != undefined) {
            var a = document.createElement("a");
            a.href = entry.report;
            a.className = "click";
            a.innerHTML = "Read Report";
            button_row.appendChild(a);
        }
        block.appendChild(button_row);

        body[0].appendChild(block);
    }
}

